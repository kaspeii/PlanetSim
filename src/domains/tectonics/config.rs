use bevy::prelude::*;

#[derive(Resource, Clone)]
pub struct TectonicsConfig {
    // === Базовые параметры плит ===
    /// Общее количество тектонических плит на планете
    pub num_plates: usize,
    /// Вероятность того, что сгенерированная плита будет континентальной (от 0.0 до 1.0)
    pub continental_ratio: f64,

    // === Параметры макро-шума и искажения (Domain Warping) ===
    /// Сила искажения границ плит (чем больше, тем сильнее извиваются разломы)
    pub warp_strength: f32,
    /// Масштаб (частота) шума искажения
    pub warp_scale: f64,
    /// Смещения по осям X, Y, Z для 3D-шума искажения (чтобы слои шума не совпадали)
    pub warp_offsets: [[f64; 3]; 3],

    // === Базовые параметры тектоники ===
    /// Максимальная дистанция от границы разлома, на которой проявляется тектоническая активность
    pub edge_threshold: f32,
    /// Базовая высота для континентальных плит (суша)
    pub cont_base_height: f32,
    /// Базовая высота для океанических плит (дно океана)
    pub ocean_base_height: f32,

    // === Настройки генерации плит ===
    /// Количество попыток найти наиболее удаленную точку при генерации центров плит
    pub plate_dir_iterations: usize,
    /// Минимальная скорость вращения плиты вокруг полюса Эйлера
    pub angular_vel_min: f32,
    /// Максимальная скорость вращения плиты вокруг полюса Эйлера
    pub angular_vel_max: f32,
    /// Малая константа (эпсилон) для предотвращения деления на ноль при расчете весов на тройных стыках
    pub weight_epsilon: f32,

    // === Дистанция и смещения для базовых высот на границах (Плавные шельфы и переходы) ===
    /// Радиус сглаживания базовой высоты между Континентом и Океаном
    pub base_co_dist: f32,
    /// Смещение высоты (спуск к воде) на границе Континент-Океан
    pub base_co_offset: f32,
    /// Радиус сглаживания базовой высоты между Океаном и Континентом
    pub base_oc_dist: f32,
    /// Смещение высоты (подъем шельфа) на границе Океан-Континент
    pub base_oc_offset: f32,
    /// Радиус сглаживания базовой высоты между двумя Континентами
    pub base_cc_dist: f32,
    /// Поднятие базового плато при столкновении двух континентов
    pub base_cc_offset: f32,
    /// Радиус сглаживания базовой высоты между двумя Океанами
    pub base_oo_dist: f32,
    /// Небольшое поднятие дна на стыке двух океанов
    pub base_oo_offset: f32,

    // === Общий шум на тектонических границах (Горы) ===
    /// Масштаб (частота) горного шума на разломах
    pub boundary_noise_scale: f64,
    /// Базовая (минимальная) составляющая горного шума (чтобы хребты не исчезали полностью)
    pub boundary_noise_base: f32,
    /// Амплитуда (разброс) горного шума (насколько сильно варьируется высота пиков)
    pub boundary_noise_amp: f32,

    // === 1. Коллизия континент-континент (Гималаи) ===
    /// Частота складок гор (синусоиды) при коллизии континентов
    pub cc_col_freq: f32,
    /// Базовый вес высоты горной цепи
    pub cc_col_base: f32,
    /// Множитель, увеличивающий высоту гор ближе к центру разлома
    pub cc_col_f_mult: f32,
    /// Общая амплитуда (высота) гор при континентальной коллизии
    pub cc_col_amp: f32,

    // === 2. Рифтогенез континентов (Восточная Африка) ===
    /// Показатель степени для центрального провала (грабена) рифта. Чем больше, тем шире долина.
    pub cc_rift_graben_pow: i32,
    /// Глубина центрального провала континентального рифта
    pub cc_rift_graben_amp: f32,
    /// Высота боковых поднятий (горстов) по краям рифта
    pub cc_rift_horst_amp: f32,
    /// Общий множитель выраженности континентального рифта
    pub cc_rift_total_amp: f32,

    // === 3. Субдукция (сторона континента - Анды) ===
    /// Отступ береговых гор вглубь материка от линии разлома
    pub co_col_offset: f32,
    /// Масштабирование ширины зоны береговых гор
    pub co_col_scale: f32,
    /// Высота береговых горных хребтов
    pub co_col_amp: f32,

    // === 4. Рифт континент-океан ===
    /// Отступ переходной зоны разлома от края континента
    pub co_rift_offset: f32,
    /// Масштабирование ширины разлома континент-океан
    pub co_rift_scale: f32,
    /// Глубина рифта на границе континента и океана
    pub co_rift_amp: f32,

    // === 5. Субдукция (сторона океана - глубоководный желоб) ===
    /// Смещение центра желоба относительно границы плит
    pub oc_col_center: f32,
    /// Ширина (масштаб) глубоководного желоба
    pub oc_col_scale: f32,
    /// Глубина океанического желоба
    pub oc_col_amp: f32,

    // === 6. Субдукция (два океана - Островные дуги) ===
    /// Амплитуда (высота) подводных хребтов и островных дуг
    pub oo_col_amp: f32,

    // === 7. Спрединг океанов (Срединно-океанические хребты) ===
    /// Степень для осевого ущелья спрединга (больше = более узкая и резкая расщелина)
    pub oo_rift_axial_pow: i32,
    /// Глубина центрального ущелья хребта
    pub oo_rift_axial_amp: f32,
    /// Высота параллельных валов хребта по краям расщелины
    pub oo_rift_ridge_amp: f32,
    /// Общий множитель высоты срединно-океанического хребта
    pub oo_rift_total_amp: f32,
    /// Базовая доля высоты хребта, не зависящая от шума
    pub oo_rift_noise_base: f32,
    /// Доля высоты хребта, модулируемая горным шумом
    pub oo_rift_noise_mult: f32,

    // === Горячие точки (Вулканы / Плюмы) ===
    /// Количество плюмов на планете
    pub hotspot_count: i32,
    /// Минимальное количество вулканов в одной цепи плюма
    pub hotspot_chain_min: usize,
    /// Максимальное количество вулканов в одной цепи плюма
    pub hotspot_chain_max: usize,
    /// Шаг по времени (расстояние) между извержениями вулканов
    pub hotspot_time_step: f32,
    /// Минимальная базовая высота нового вулкана
    pub hotspot_height_min: f32,
    /// Максимальная базовая высота нового вулкана
    pub hotspot_height_max: f32,
    /// Степень эрозии со временем (снижения высоты старых вулканов)
    pub hotspot_erosion_pow: f32,
    /// Базовый радиус нового вулкана
    pub hotspot_radius_base: f32,
    /// Прирост радиуса старых вулканов (оседание и расползание)
    pub hotspot_radius_growth: f32,
    /// Показатель степени для профиля склона вулкана (2 = вогнутые склоны, как у Фудзи)
    pub volcano_profile_pow: i32,
    /// Масштаб (частота) шума, искажающего склоны вулкана
    pub volcano_noise_scale: f64,
    /// Базовая составляющая шума вулкана (сохраняет основную форму конуса)
    pub volcano_noise_base: f32,
    /// Амплитуда шума на склонах вулкана (насколько они неровные)
    pub volcano_noise_mult: f32,

    // === Детализация рельефа (Мелкий глобальный шум) ===
    /// Масштаб (частота) мелкого шума, покрывающего всю планету
    pub detail_noise_scale: f64,
    /// Амплитуда мелкого глобального шума (шероховатость)
    pub detail_noise_amp: f32,
    /// Глобальный лимит максимальной глубины (защита от проколов геометрии)
    pub elevation_min_clamp: f32,

    // === Сглаживание (Клеточный автомат) ===
    /// Сила финального сглаживания (диффузии) высот между соседними гексами
    pub diffusion_strength: f32,
}

